import pandas as pd
import plotly.express as px
import streamlit as st
from datetime import timedelta


# =========================================================
# 기본 설정
# =========================================================

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide",
)

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.write(
    "KOBIS 일별 박스오피스 데이터를 시간의 흐름에 따라 살펴보는 그래프 도감입니다."
)


# =========================================================
# 데이터 불러오기
# =========================================================

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/modudata/"
    "main/data/kobis_daily.csv"
)


@st.cache_data
def load_data():
    """
    GitHub에서 CSV 데이터를 불러오고
    그래프에 사용할 수 있도록 자료형을 정리합니다.
    """

    df = pd.read_csv(DATA_URL)

    # -----------------------------------------------------
    # 날짜
    # -----------------------------------------------------
    # CSV의 날짜는 20250901처럼 하이픈 없는 8자리 숫자입니다.
    # 이를 실제 날짜(datetime)로 변환합니다.

    df["날짜"] = pd.to_datetime(
        df["날짜"].astype(str),
        format="%Y%m%d",
        errors="coerce",
    )

    # -----------------------------------------------------
    # 숫자 열
    # -----------------------------------------------------

    numeric_columns = [
        "순위",
        "영화코드",
        "일관객",
        "누적관객",
        "스크린수",
        "상영횟수",
    ]

    for column in numeric_columns:
        df[column] = pd.to_numeric(
            df[column],
            errors="coerce",
        )

    # 날짜가 변환되지 않은 잘못된 행은 제거합니다.
    df = df.dropna(subset=["날짜"])

    return df


# =========================================================
# 데이터 로딩
# =========================================================

try:
    df = load_data()

except Exception as e:
    st.error(
        "데이터를 불러오는 중 문제가 발생했습니다.\n\n"
        f"오류 내용: {e}"
    )
    st.stop()


# =========================================================
# 데이터 기본 정보
# =========================================================

min_date = df["날짜"].min()
max_date = df["날짜"].max()

movie_count = df["영화코드"].nunique()

st.caption(
    f"데이터 기간: {min_date:%Y년 %m월 %d일} ~ "
    f"{max_date:%Y년 %m월 %d일} · "
    f"영화 {movie_count:,}편 · "
    f"총 {len(df):,}개 기록"
)


# =========================================================
# 그래프 1
# 영화별 일관객 변화
# =========================================================

st.divider()

st.header("1. 영화별 일관객 변화")

st.write(
    "영화를 하나 선택하면 그 영화가 10위권에 기록된 날짜별 "
    "일관객 변화를 볼 수 있습니다."
)


# ---------------------------------------------------------
# 영화 목록 만들기
# ---------------------------------------------------------
#
# 영화명만 사용하면 같은 제목의 다른 영화가 합쳐질 가능성이
# 있으므로 영화코드를 함께 사용합니다.
#
# 화면에는
#
# 영화명
#
# 으로 보여주고, 실제 필터링은 영화코드로 합니다.


movie_info = (
    df[
        [
            "영화코드",
            "영화명",
        ]
    ]
    .drop_duplicates()
    .sort_values("영화명")
)


# 영화 선택용 딕셔너리
movie_options = {}

for _, row in movie_info.iterrows():
    movie_code = int(row["영화코드"])
    movie_name = str(row["영화명"])

    movie_options[movie_code] = movie_name


selected_movie_code = st.selectbox(
    "🎬 영화를 선택하세요",
    options=list(movie_options.keys()),
    format_func=lambda code: movie_options[code],
)


selected_movie_name = movie_options[selected_movie_code]


# ---------------------------------------------------------
# 선택한 영화 데이터
# ---------------------------------------------------------

movie_df = (
    df[df["영화코드"] == selected_movie_code]
    .sort_values("날짜")
    .copy()
)


# ---------------------------------------------------------
# 선택한 영화의 데이터 정보
# ---------------------------------------------------------

record_count = len(movie_df)

first_date = movie_df["날짜"].min()
last_date = movie_df["날짜"].max()


st.caption(
    f"선택한 영화: {selected_movie_name} · "
    f"10위권 기록 {record_count:,}일 · "
    f"{first_date:%Y-%m-%d} ~ {last_date:%Y-%m-%d}"
)


# =========================================================
# Plotly 그래프
# =========================================================

fig = px.line(
    movie_df,
    x="날짜",
    y="일관객",
    markers=True,
    labels={
        "날짜": "날짜",
        "일관객": "일관객수(명)",
    },
)


# ---------------------------------------------------------
# 그래프 제목
# ---------------------------------------------------------

fig.update_layout(
    title=f"{selected_movie_name} · 날짜별 일관객",
    height=500,
    margin=dict(
        l=20,
        r=20,
        t=60,
        b=20,
    ),
)


# ---------------------------------------------------------
# 마우스 오버
# ---------------------------------------------------------

fig.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}"
        "<br>"
        "일관객: %{y:,}명"
        "<extra></extra>"
    )
)


# ---------------------------------------------------------
# 날짜축
# ---------------------------------------------------------

if record_count == 1:
    # 데이터가 하루밖에 없는 영화의 경우
    # Plotly가 시간축을 나노초 단위처럼 이상하게 확장하지
    # 않도록 날짜 앞뒤에 하루씩 여유를 줍니다.

    single_date = movie_df["날짜"].iloc[0]

    fig.update_xaxes(
        range=[
            single_date - timedelta(days=1),
            single_date + timedelta(days=1),
        ],
        tickformat="%Y-%m-%d",
    )

else:
    fig.update_xaxes(
        type="date",
        tickformat="%m/%d",
    )


# ---------------------------------------------------------
# Y축
# ---------------------------------------------------------

fig.update_yaxes(
    separatethousands=True,
    title_text="일관객수(명)",
)


# ---------------------------------------------------------
# 그래프 출력
# ---------------------------------------------------------

st.plotly_chart(
    fig,
    use_container_width=True,
)


# =========================================================
# 그래프 해석
# =========================================================

st.markdown("### 이 그래프로 알 수 있는 것")

st.info(
    "영화가 10위권에 기록된 날짜별 일관객 변화를 통해 "
    "시간이 지나면서 관객수가 어떻게 변했는지 살펴볼 수 있습니다."
)


# =========================================================
# 그래프 2
# =========================================================

st.divider()

st.header("2. 다음 그래프")

st.write(
    "앞으로 새로운 그래프를 이 영역에 추가합니다."
)


