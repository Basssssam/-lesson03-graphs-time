import pandas as pd
import plotly.express as px
import streamlit as st


# =========================================================
# 기본 설정
# =========================================================

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide",
)

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.caption(
    "KOBIS 일별 박스오피스 데이터를 시간의 흐름에 따라 살펴봅니다."
)


# =========================================================
# 데이터 불러오기
# =========================================================

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/modudata/"
    "main/data/kobis_daily.csv"
)


@st.cache_data
def load_data():

    df = pd.read_csv(DATA_URL)

    # -----------------------------------------------------
    # 날짜 변환
    # -----------------------------------------------------

    df["날짜"] = pd.to_datetime(
        df["날짜"].astype(str),
        format="%Y%m%d",
        errors="coerce",
    )

    # -----------------------------------------------------
    # 숫자 데이터 변환
    # -----------------------------------------------------

    numeric_columns = [
        "순위",
        "영화코드",
        "일관객",
        "누적관객",
        "스크린수",
        "상영횟수",
    ]

    for column in numeric_columns:
        df[column] = pd.to_numeric(
            df[column],
            errors="coerce",
        )

    # 날짜가 잘못된 행 제거
    df = df.dropna(subset=["날짜"])

    return df


# =========================================================
# 데이터 가져오기
# =========================================================

try:
    df = load_data()

except Exception as e:

    st.error(
        "데이터를 불러오지 못했습니다.\n\n"
        f"오류 내용: {e}"
    )

    st.stop()


# =========================================================
# 데이터 기본 정보
# =========================================================

min_date = df["날짜"].min()
max_date = df["날짜"].max()

movie_count = df["영화코드"].nunique()

st.caption(
    f"데이터 기간: "
    f"{min_date:%Y-%m-%d} ~ {max_date:%Y-%m-%d}"
    f" · 영화 {movie_count:,}편"
)


# =========================================================
# 그래프 1
# =========================================================

st.divider()

st.header("1. 영화별 일관객 변화")

st.write(
    "영화를 선택하면 해당 영화가 10위권에 기록된 "
    "날짜별 일관객 변화를 볼 수 있습니다."
)


# =========================================================
# 영화 선택 목록
# =========================================================

# 영화코드와 영화명을 한 쌍으로 사용합니다.
movie_info = (
    df[
        [
            "영화코드",
            "영화명",
        ]
    ]
    .drop_duplicates()
    .sort_values("영화명")
)


# 영화코드 → 영화명
movie_options = {
    int(row["영화코드"]): str(row["영화명"])
    for _, row in movie_info.iterrows()
}


selected_movie_code = st.selectbox(
    "🎬 영화를 선택하세요",
    options=list(movie_options.keys()),
    format_func=lambda code: movie_options[code],
)


selected_movie_name = movie_options[selected_movie_code]


# =========================================================
# 선택한 영화 데이터
# =========================================================

movie_df = (
    df[df["영화코드"] == selected_movie_code]
    .sort_values("날짜")
    .copy()
)


# 혹시 같은 영화가 같은 날짜에 여러 번 존재한다면
# 날짜별로 하나의 값만 사용합니다.
movie_df = (
    movie_df
    .groupby("날짜", as_index=False)
    .agg(
        {
            "일관객": "sum",
        }
    )
    .sort_values("날짜")
)


# =========================================================
# 데이터 정보
# =========================================================

record_count = len(movie_df)

first_date = movie_df["날짜"].min()
last_date = movie_df["날짜"].max()


st.caption(
    f"선택한 영화: {selected_movie_name} · "
    f"10위권 기록 {record_count:,}일 · "
    f"{first_date:%Y-%m-%d} ~ {last_date:%Y-%m-%d}"
)


# =========================================================
# 그래프 만들기
# =========================================================

fig = px.line(
    movie_df,
    x="날짜",
    y="일관객",
    markers=True,
)


# =========================================================
# 그래프 제목
# =========================================================

fig.update_layout(
    title=f"{selected_movie_name} · 날짜별 일관객",
    height=500,

    margin=dict(
        l=20,
        r=20,
        t=70,
        b=30,
    ),

    xaxis_title="날짜",
    yaxis_title="일관객수(명)",
)


# =========================================================
# 마우스 오버
# =========================================================

fig.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}"
        "<br>"
        "일관객: %{y:,}명"
        "<extra></extra>"
    )
)


# =========================================================
# 날짜 축 설정
# =========================================================

if record_count == 1:

    # -----------------------------------------------------
    # 하루짜리 데이터
    # -----------------------------------------------------
    #
    # 예:
    # 2025-09-24 하루만 데이터가 있는 경우
    #
    # 09-23 / 09-24 / 09-25
    #
    # 세 날짜만 눈금으로 표시합니다.
    #
    # Plotly가 시간 단위로 눈금을 자동 생성하지 못하도록
    # dtick을 정확히 하루로 지정합니다.

    selected_day = movie_df["날짜"].iloc[0]

    start_day = selected_day - pd.Timedelta(days=1)
    end_day = selected_day + pd.Timedelta(days=1)

    fig.update_xaxes(
        range=[
            start_day,
            end_day,
        ],

        dtick=24 * 60 * 60 * 1000,

        tick0=start_day,

        tickformat="%m/%d",

        type="date",

        fixedrange=False,
    )


else:

    # -----------------------------------------------------
    # 여러 날짜 데이터
    # -----------------------------------------------------

    date_span = (
        movie_df["날짜"].max()
        - movie_df["날짜"].min()
    ).days

    # 데이터가 짧으면 매일 표시
    if date_span <= 14:

        fig.update_xaxes(
            type="date",
            dtick=24 * 60 * 60 * 1000,
            tickformat="%m/%d",
        )

    # 15~60일 정도라면 일주일 간격
    elif date_span <= 60:

        fig.update_xaxes(
            type="date",
            dtick=7 * 24 * 60 * 60 * 1000,
            tickformat="%m/%d",
        )

    # 더 긴 기간이면 자동 축 사용
    else:

        fig.update_xaxes(
            type="date",
            tickformat="%m/%d",
        )


# =========================================================
# Y축 설정
# =========================================================

fig.update_yaxes(
    separatethousands=True,
)


# =========================================================
# 그래프 출력
# =========================================================

st.plotly_chart(
    fig,
    use_container_width=True,
)


# =========================================================
# 이 그래프로 알 수 있는 것
# =========================================================

st.markdown(
    "### 이 그래프로 알 수 있는 것"
)

st.info(
    "영화가 10위권에 기록된 날짜별 일관객 변화를 통해 "
    "시간이 지나면서 관객수가 어떻게 변했는지 살펴볼 수 있습니다."
)


# =========================================================
# 그래프 2
# =========================================================

st.divider()

st.header("2. 다음 그래프")

st.write(
    "앞으로 새로운 그래프를 이 영역에 추가합니다."
)


